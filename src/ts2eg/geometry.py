"""Geometry helpers for payoff operators and replicator dynamics.

Replicator dynamics identify payoff matrices only up to transformations of the
form ``A -> A + 1 c.T``.  The canonical representative used by :mod:`ts2eg` is
therefore obtained by left multiplication with the centering projector.
"""

from __future__ import annotations

import numpy as np


def centering_projector(k: int) -> np.ndarray:
    """Return ``M = I - 1 1.T / k`` for a positive integer dimension ``k``.

    The returned matrix is the orthogonal projector onto the subspace whose
    coordinates sum to zero.

    Parameters
    ----------
    k:
        Positive strategy-space dimension.

    Raises
    ------
    ValueError
        If ``k`` is not a positive integer.
    """
    if isinstance(k, (bool, np.bool_)) or not isinstance(k, (int, np.integer)) or k < 1:
        raise ValueError("k must be a positive integer")
    one = np.ones((int(k), 1), dtype=float)
    return np.eye(int(k), dtype=float) - (one @ one.T) / int(k)


def _validate_payoff_operator(A: np.ndarray) -> np.ndarray:
    """Return a finite floating-point square payoff operator."""
    operator = np.asarray(A, dtype=float)
    if operator.ndim != 2 or operator.shape[0] != operator.shape[1] or operator.shape[0] == 0:
        raise ValueError("A must be a non-empty square matrix")
    if not np.all(np.isfinite(operator)):
        raise ValueError("A must contain only finite values")
    return operator


def canonicalize_payoff_operator(A: np.ndarray) -> np.ndarray:
    """Return the canonical payoff operator ``B = M @ A``.

    Here ``M`` is :func:`centering_projector` for the strategy dimension.  The
    result satisfies ``1.T @ B == 0`` up to floating-point error and generates
    the same replicator vector field as ``A``.  No right-centering is applied:
    imposing ``B @ 1 == 0`` changes the vector field in general.

    Parameters
    ----------
    A:
        Finite, non-empty square payoff operator.
    """
    operator = _validate_payoff_operator(A)
    return centering_projector(operator.shape[0]) @ operator


def replicator_field(A: np.ndarray, x: np.ndarray) -> np.ndarray:
    """Evaluate the replicator vector field generated by ``A`` at mixture ``x``.

    The field is

    ``F_i(x) = x_i * ((A @ x)_i - x.T @ A @ x)``.

    Parameters
    ----------
    A:
        Finite, non-empty square payoff operator.
    x:
        Finite one-dimensional probability vector matching ``A``.

    Raises
    ------
    ValueError
        If ``A`` is invalid or ``x`` is not a point on the corresponding
        probability simplex.
    """
    operator = _validate_payoff_operator(A)
    mixture = np.asarray(x, dtype=float)
    k = operator.shape[0]
    if mixture.ndim != 1 or mixture.shape[0] != k:
        raise ValueError(f"x must be a one-dimensional vector of length {k}")
    if not np.all(np.isfinite(mixture)):
        raise ValueError("x must contain only finite values")
    if np.any(mixture < 0.0) or not np.isclose(
        float(np.sum(mixture)), 1.0, rtol=1e-10, atol=1e-12
    ):
        raise ValueError("x must be a probability vector with nonnegative entries summing to one")

    payoffs = operator @ mixture
    mean_payoff = float(mixture @ payoffs)
    return mixture * (payoffs - mean_payoff)
